// Funzioni per la persistenza degli esercizi personalizzati dell'utente
const CUSTOM_EXERCISES_STORAGE_KEY = 'gym_app_custom_exercises_v1';

export function getUserCustomExercises(): ExerciseDefinition[] {
  try {
    const raw = localStorage.getItem(CUSTOM_EXERCISES_STORAGE_KEY);
    const list: ExerciseDefinition[] = raw ? JSON.parse(raw) : [];
    return list.map((item) => ({ ...item, isCustom: true }));
  } catch {
    return [];
  }
}

export function saveUserCustomExercise(def: ExerciseDefinition): void {
  try {
    const existing = getUserCustomExercises();
    const itemToSave: ExerciseDefinition = { ...def, isCustom: true };
    const updated = [itemToSave, ...existing.filter((e) => e.id !== def.id)];
    localStorage.setItem(CUSTOM_EXERCISES_STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Failed to save custom exercise:', err);
  }
}

export function deleteUserCustomExercise(id: string): void {
  try {
    const existing = getUserCustomExercises();
    const updated = existing.filter((e) => e.id !== id);
    localStorage.setItem(CUSTOM_EXERCISES_STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Failed to delete custom exercise:', err);
  }
}

export function getAllExerciseDefinitions(): ExerciseDefinition[] {
  const custom = getUserCustomExercises();
  return [...custom, ...BASE_EXERCISE_DATASET];
}

export const EXERCISE_DATASET = getAllExerciseDefinitions();
